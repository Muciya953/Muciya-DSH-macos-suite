		/**
		* Put `/name` tokens into the Session's composer instead of sending them.
		*
		* The tokens are literal draft text. The composer's own text-ref decoration
		* (`scanTextRefs` over the live trigger lexicon in `ui-conversation`) paints
		* a `/name` whose name is on the skill lexicon as a chip, so the skill reads
		* as a link in the composer and the Host only loads it when the user actually
		* sends the message — nothing is invoked by inserting.
		*
		* The draft goes through the Session's input shell, the same face the
		* composer's own draft-restore path uses, so an existing draft is kept and
		* the caret lands at the end. Creating the session's input-trigger controller
		* warms its source roster once, which is what feeds that lexicon.
		* @param dependency - `{ sessions, conversation, inputTriggers }` faces from the plugin context.
		* @param sessionId - Session whose composer receives the tokens.
		* @param names - one skill name, or several to insert in one go.
		* @param signal - caller lifetime; aborted when the panel unmounts.
		* @returns the new draft text.
		*/
		function insertSkills(dependency, sessionId, names, signal) {
			const list = (Array.isArray(names) ? names : [names]).filter((name) => typeof name === "string" && name !== "");
			if (list.length === 0) throw new Error("no skill to insert");
			const tokens = list.map((name) => `/${name}`).join(" ");
			return dependency.sessions.using(sessionId, { source: RETAIN_SOURCE, signal }, (reference) => {
				if (signal?.aborted === true) throw new Error("skill insertion was aborted");
				const shell = dependency.conversation.input.shell(sessionId);
				const scope = reference?.binding?.ctx;
				if (scope !== undefined)
					try {
						dependency.inputTriggers.sessionOf(scope);
					} catch {
						/* the composer warms its own roster when it mounts */
					}
				const text = `${tokens} `;
				/** The composer's own insertion: caret-anchored, chip-preserving, refused while submitting. */
				const span = shell.actions.captureInsertion?.();
				if (span !== undefined && shell.actions.insertText(text, span) === true) return text;
				/** Fallback for a busy or stale composer: rewrite the draft, keeping what it held. */
				const current = String(shell.state.getSnapshot()?.draft ?? "");
				const next = current.trim() === "" ? text : `${current.replace(/\s+$/, "")} ${text}`;
				shell.actions.setDraft(next);
				return next;
			});
		}
