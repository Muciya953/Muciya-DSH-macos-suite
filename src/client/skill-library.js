/**
* Choose the Session whose skill catalog this panel shows.
*
* `retainedBy.mainView` is the sidebar workspace browser's selection: it
* owns that retention for as long as a Session stays selected, panel or no
* panel, so a user browsing global panels still resolves to the Session they
* were reading — the catalog shown and the invoke target are the same
* Session the Conversation returns to. Without a selection the most recently
* active durable Session stands in; subagent rows only win when nothing else
* exists.
* @param snapshot - the Session catalog snapshot (`useSessions` selector payload).
* @returns the chosen Session row, or undefined for an empty catalog.
*/
function pickSession(snapshot) {
	const byId = snapshot?.byId ?? {};
	const rows = Object.values(byId).filter((row) => row !== null && row !== undefined);
	const main = rows.find((row) => (row.retainedBy?.mainView ?? 0) > 0);
	if (main !== undefined) return main;
	const durable = rows.filter((row) => row.origin !== "subagent");
	const pool = durable.length > 0 ? durable : rows;
	return pool.slice().sort((a, b) => (b.updatedAt ?? 0) - (a.updatedAt ?? 0))[0];
}
/**
* Fold a family of skills onto its entry skill.
*
* A skill whose name is `<other>-<suffix>` and whose `<other>` is also
* installed is a member of that family (the HyperFrames suite is one), so the
* library shows a single row for the family and lists the members on demand.
* Structure comes from the whole catalog, never from search results, and a
* member is emitted by its parent's row — so a family is always one group at
* the entry skill's position, whatever order the catalog arrives in.
* @param rows - catalog rows in host order.
* @returns entries: `{ kind: "row", skill }` or `{ kind: "group", skill, members }`.
*/
function groupSkills(rows) {
	const list = Array.isArray(rows) ? rows.filter((row) => typeof row?.name === "string" && row.name !== "") : [];
	const names = new Set(list.map((row) => row.name));
	/** The installed skill that owns this one: an explicit family table first, then the longest name prefix. */
	const parentOf = (name) => {
		const declared = FAMILY_PARENT[name];
		let parent = declared !== undefined && names.has(declared) ? declared : undefined;
		for (const candidate of names) {
			if (candidate === name || !name.startsWith(`${candidate}-`)) continue;
			if (parent === undefined || candidate.length > parent.length) parent = candidate;
		}
		return parent;
	};
	/** The topmost installed ancestor: a deeper descendant folds into the same family. */
	const rootOf = (name) => {
		let root;
		const seen = new Set([name]);
		for (let current = parentOf(name); current !== undefined && !seen.has(current); current = parentOf(current)) {
			seen.add(current);
			root = current;
		}
		return root;
	};
	const membersOf = new Map();
	for (const row of list) {
		const root = rootOf(row.name);
		if (root === undefined) continue;
		const members = membersOf.get(root);
		if (members === undefined) membersOf.set(root, [row]);
		else members.push(row);
	}
	const entries = [];
	const claimed = new Set();
	for (const members of membersOf.values()) for (const member of members) claimed.add(member.name);
	for (const row of list) {
		if (claimed.has(row.name)) continue;
		const members = membersOf.get(row.name);
		if (members === undefined) entries.push({ kind: "row", skill: row });
		else entries.push({ kind: "group", name: row.name, skill: row, members });
	}
	return entries;
}
/** Whether one skill answers a search query (the loader's own name ranking). */
function matchesQuery(skill, query) {
	return primitives.rankByName([skill], query).length > 0;
}
/** Read one error's message without assuming an Error instance crossed a remote boundary. */
function messageOf(error) {
	if (error instanceof Error) return error.message;
	return typeof error === "string" ? error : String(error);
}
/**
* A failed reload must not throw away what the panel already knows. When rows
* are on screen they stay, the failure turns into a `stale` attribute, and
* `lastGoodAt` remembers when they were last true. Only a first load with
* nothing to show becomes the `error` face.
*/
function failureTransition(previous, error) {
	const rows = Array.isArray(previous?.rows) ? previous.rows : [];
	const lastGoodAt = typeof previous?.lastGoodAt === "number" ? previous.lastGoodAt : null;
	const forSession = previous?.forSession;
	const message = messageOf(error);
	if (rows.length === 0) return { status: "error", stale: false, rows, error: message, lastGoodAt, forSession };
	return { status: "ready", stale: true, rows, error: message, lastGoodAt, forSession };
}
/** Which face the panel paints: one branch per state, never two at once. */
function bodyKind(state) {
	const status = typeof state?.status === "string" ? state.status : "idle";
	const rows = Array.isArray(state?.rows) ? state.rows : [];
	if (status === "idle") return "idle";
	if (status === "loading" && rows.length === 0) return "loading";
	if (status === "error") return "failed";
	if (status === "ready" && state.stale === true) return "stale";
	return "list";
}
/**
* Read the skill catalog visible to one Session.
*
* `sessions.using` retains (and opens) the Session for the duration of the
* read, so this works for any catalogued Session, not only an already-open
* one. The abort signal covers both the retention and the Remote call.
* @param dependency - `{ sessions, skills }` faces captured from the plugin context.
* @param sessionId - Session whose cwd and preset select the catalog view.
* @param signal - caller lifetime; aborted when the panel unmounts or switches Session.
* @returns the user-invocable skill rows.
*/
function loadSkills(dependency, sessionId, signal) {
	return dependency.sessions.using(sessionId, { source: RETAIN_SOURCE, signal }, async (reference) => {
		if (signal?.aborted === true) throw new Error("skill catalog read was aborted");
		const state = reference?.binding?.session?.getSnapshot?.();
		if (state !== undefined && state.openState !== "open") throw state.openError ?? new Error(`session "${sessionId}" is not open`);
		const result = await dependency.skills.list({ sessionId }, signal);
		if (signal?.aborted === true) throw new Error("skill catalog read was aborted");
		if (result?.ok !== true) throw new Error(result?.error === undefined ? `skills/list failed for session "${sessionId}"` : `skills/list failed: ${result.error.code}: ${result.error.message}`);
		const rows = result.value?.skills;
		return Array.isArray(rows) ? rows : [];
	});
}
/**
* Put `/name` tokens into the Session's composer instead of sending them.
*
* The tokens are literal draft text. The composer's own text-ref decoration
* (`scanTextRefs` over the live trigger lexicon in `ui-conversation`) paints
* a `/name` whose name is on the skill lexicon as a chip, so the skill reads
* as a link in the composer and the Host only loads it when the user actually
* sends the message — nothing is invoked by inserting.
*
* The draft goes through the Session's input shell, the same face the
* composer's own draft-restore path uses, so an existing draft is kept and
* the caret lands at the end. Creating the session's input-trigger controller
* warms its source roster once, which is what feeds that lexicon.
* @param dependency - `{ sessions, conversation, inputTriggers }` faces from the plugin context.
* @param sessionId - Session whose composer receives the tokens.
* @param names - one skill name, or several to insert in one go.
* @param signal - caller lifetime; aborted when the panel unmounts.
* @returns the new draft text.
*/
function insertSkills(dependency, sessionId, names, signal) {
	const list = (Array.isArray(names) ? names : [names]).filter((name) => typeof name === "string" && name !== "");
	if (list.length === 0) throw new Error("no skill to insert");
	const tokens = list.map((name) => `/${name}`).join(" ");
	return dependency.sessions.using(sessionId, { source: RETAIN_SOURCE, signal }, (reference) => {
		if (signal?.aborted === true) throw new Error("skill insertion was aborted");
		const shell = dependency.conversation.input.shell(sessionId);
		const scope = reference?.binding?.ctx;
		if (scope !== undefined)
			try {
				dependency.inputTriggers.sessionOf(scope);
			} catch {
				/* the composer warms its own roster when it mounts */
			}
		const text = `${tokens} `;
		/** The composer's own insertion: caret-anchored, chip-preserving, refused while submitting. */
		const span = shell.actions.captureInsertion?.();
		if (span !== undefined && shell.actions.insertText(text, span) === true) return text;
		/** Fallback for a busy or stale composer: rewrite the draft, keeping what it held. */
		const current = String(shell.state.getSnapshot()?.draft ?? "");
		const next = current.trim() === "" ? text : `${current.replace(/\s+$/, "")} ${text}`;
		shell.actions.setDraft(next);
		return next;
	});
}
