/** One skill row: a plain skill, or a family entry with its expander and member count. */
function SkillRow({ skill, pending, failure, busy, onInvoke, t, nested, badge, caret, all }) {
	const name = typeof skill.name === "string" ? skill.name : "";
	const description = typeof skill.description === "string" ? skill.description : "";
	const whenToUse = typeof skill.whenToUse === "string" ? skill.whenToUse : "";
	/** Skill summaries are authored as three lines: a one-sentence role, then two lines of function. */
	const descriptionLines = description.split("\n").map((line) => line.trim()).filter((line) => line !== "");
	return h("li", { className: `dsl-skilllib-row${nested === true ? " dsl-skilllib-rowNested" : ""}` }, [
		caret === undefined
			? null
			: h(
					"button",
					{
						key: "caret",
						type: "button",
						className: "dsl-skilllib-caret",
						"aria-expanded": caret.expanded === true ? "true" : "false",
						"aria-label": caret.label,
						onClick: caret.onToggle
					},
					h(caret.expanded === true ? primitives.IconChevronDownOutlineRegular : primitives.IconChevronRightOutlineRegular, { size: 14 })
				),
		h("span", { className: "dsl-skilllib-glyph", key: "glyph", "aria-hidden": "true" }, h(primitives.IconSkillOutlineRegular, { size: 16 })),
		h("div", { className: "dsl-skilllib-rowMain", key: "main" }, [
			h("div", { className: "dsl-skilllib-rowHead", key: "head" }, [
				h("code", { className: "dsl-skilllib-name", key: "name" }, `/${name}`),
				skill.modelInvocable === false ? h("span", { className: "dsl-skilllib-tag", key: "tag" }, t("userOnly")) : null
			]),
			descriptionLines.length === 0
				? null
				: h(
						"div",
						{ className: "dsl-skilllib-desc", key: "desc", title: description },
						descriptionLines.map((line, index) => h("p", { className: index === 0 ? "dsl-skilllib-descLead" : "dsl-skilllib-descLine", key: `line-${index}` }, line))
					),
			whenToUse === "" ? null : h("p", { className: "dsl-skilllib-whenToUse", key: "when", title: whenToUse }, whenToUse),
			failure === undefined ? null : h("p", { className: "dsl-skilllib-rowError", key: "error" }, t("invoke.failed", { reason: failure }))
		]),
		h(
			"div",
			{ className: "dsl-skilllib-rowEnd", key: "end" },
			badge === undefined ? null : h("span", { className: "dsl-skilllib-badge", key: "badge" }, badge),
			all === undefined
				? null
				: h(
						primitives.Button,
						{
							key: "all",
							variant: "outline",
							size: "sm",
							icon: h(primitives.IconFlatListOutlineRegular, { size: 13 }),
							"aria-label": all.label,
							disabled: all.disabled === true,
							onClick: all.onClick
						},
						all.pending === true ? t("invoking") : t("group.all")
					),
			h(
				primitives.Button,
				{
					variant: "outline",
					size: "sm",
					icon: h(primitives.IconPaperPlaneOutlineRegular, { size: 13 }),
					"aria-label": t("invoke.label", { name }),
					disabled: pending === true || busy === true,
					onClick: () => onInvoke(skill)
				},
				pending === true ? t("invoking") : t("invoke")
			)
		)
	]);
}
/**
* The Skill Library page: the skills the selected Session can invoke,
* filterable by name and copyable as `/name` for the composer.
* @param props - slot props: `useSessions` plus this plugin's injected faces.
* @returns the panel element tree.
*/
function SkillLibraryPage(props) {
	const { useSessions, sessions, skills, layout, conversation, inputTriggers, t } = props;
	const snapshot = useSessions((state) => state);
	const session = useMemo(() => pickSession(snapshot), [snapshot]);
	const sessionId = session?.id;
	const sessionTitle = typeof session?.displayTitle === "string" && session.displayTitle !== "" ? session.displayTitle : sessionId;
	const [query, setQuery] = useState("");
	const [reloadKey, setReloadKey] = useState(0);
	const [invoking, setInvoking] = useState(void 0);
	const [invokeFailure, setInvokeFailure] = useState(void 0);
	const [expandedFamilies, setExpandedFamilies] = useState([]);
	const [state, setState] = useState({ status: "idle", stale: false, rows: [], error: void 0, lastGoodAt: null, forSession: void 0 });
	const invocation = useRef(void 0);
	useEffect(() => {
		if (sessionId === void 0) {
			setState({ status: "idle", stale: false, rows: [], error: void 0, lastGoodAt: null, forSession: void 0 });
			return void 0;
		}
		const abort = new AbortController();
		setState((previous) => ({
			status: "loading",
			rows: previous.forSession === sessionId ? previous.rows : [],
			error: void 0,
			forSession: sessionId
		}));
		loadSkills({ sessions, skills }, sessionId, abort.signal).then(
			(rows) => {
				if (abort.signal.aborted) return;
				setState({ status: "ready", stale: false, rows, error: void 0, lastGoodAt: Date.now(), forSession: sessionId });
			},
			(error) => {
				if (abort.signal.aborted) return;
				setState((previous) => failureTransition(previous, error));
			}
		);
		return () => {
			abort.abort();
		};
	}, [sessionId, reloadKey]);
	useEffect(
		() => () => {
			if (invocation.current !== void 0) invocation.current.abort();
		},
		[]
	);
	const entries = useMemo(() => groupSkills(state.rows), [state.rows]);
	const searching = query.trim() !== "";
	/** Search prunes the grouped catalog; a family stays if the entry or any member matches. */
	const shown = useMemo(() => {
		const trimmed = query.trim();
		if (trimmed === "") return entries;
		const result = [];
		for (const entry of entries) {
			if (entry.kind === "row") {
				if (matchesQuery(entry.skill, trimmed)) result.push(entry);
				continue;
			}
			const own = matchesQuery(entry.skill, trimmed);
			const members = entry.members.filter((member) => matchesQuery(member, trimmed));
			if (own || members.length > 0) result.push({ ...entry, members });
		}
		return result;
	}, [entries, query]);
	const visibleCount = shown.reduce((total, entry) => total + (entry.kind === "group" ? 1 + entry.members.length : 1), 0);
	const toggleFamily = useCallback((name) => {
		setExpandedFamilies((current) => current.includes(name) ? current.filter((entry) => entry !== name) : [...current, name]);
	}, []);
	/** Insert one skill, or a whole family, into the composer and return to it. */
	const run = useCallback(
		(key, names) => {
			if (key === "" || sessionId === undefined || invoking !== undefined) return;
			const controller = new AbortController();
			invocation.current = controller;
			setInvoking(key);
			setInvokeFailure(void 0);
			insertSkills({ sessions, conversation, inputTriggers }, sessionId, names, controller.signal).then(
				() => {
					if (controller.signal.aborted) return;
					setInvoking(void 0);
					layout.selectPanel(null);
				},
				(error) => {
					if (controller.signal.aborted) return;
					setInvoking(void 0);
					setInvokeFailure({ key, message: messageOf(error) });
				}
			);
		},
		[sessions, conversation, inputTriggers, layout, sessionId, invoking]
	);
	const onInvoke = useCallback(
		(skill) => {
			const name = typeof skill?.name === "string" ? skill.name : "";
			run(name, [name]);
		},
		[run]
	);
	const refresh = useCallback(() => {
		setReloadKey((key) => key + 1);
	}, []);
	let body;
	if (state.status === "idle") {
		body = h(StateBlock, {
			glyph: h(primitives.IconSkillOutlineRegular, { size: 20 }),
			title: t("state.noSession.title"),
			body: t("state.noSession.body")
		});
	} else if (state.status === "loading" && state.rows.length === 0) {
		body = h(StateBlock, {
			glyph: h(primitives.IconLoadingOutlineRegular, { size: 20 }),
			title: t("state.loading")
		});
	} else if (state.status === "error") {
		body = h(StateBlock, {
			glyph: h(primitives.IconWarningTriangleOutlineRegular, { size: 20 }),
			title: t("state.error.title"),
			body: state.error,
			error: true,
			action: h(primitives.Button, { variant: "outline", size: "sm", onClick: refresh }, t("state.retry"))
		});
	} else if (state.rows.length === 0) {
		body = h(StateBlock, {
			glyph: h(primitives.IconSkillOutlineRegular, { size: 20 }),
			title: t("state.none.title"),
			body: t("state.none.body")
		});
	} else if (visibleCount === 0) {
		body = h(StateBlock, {
			glyph: h(primitives.IconSearchOutlineRegular, { size: 20 }),
			title: t("state.match.title"),
			body: t("state.match.body")
		});
	} else {
		/** Row props shared by family entries and their members. */
		const rowProps = (skill, reactKey, stateKey = skill.name) => ({
			key: reactKey,
			skill,
			pending: invoking !== undefined && invoking === stateKey,
			busy: invoking !== undefined && invoking !== stateKey,
			failure: invokeFailure !== undefined && invokeFailure.key === stateKey ? invokeFailure.message : void 0,
			onInvoke,
			t
		});
		const rows = [];
		for (const entry of shown) {
			if (entry.kind === "row") {
				rows.push(h(SkillRow, rowProps(entry.skill, entry.skill.name)));
				continue;
			}
			/** A search always reveals what it matched; otherwise the family folds away. */
			const open = searching || expandedFamilies.includes(entry.name);
			const familyKey = `${entry.name}/*`;
			rows.push(
				h(SkillRow, {
					...rowProps(entry.skill, `family-${entry.name}`, entry.name),
					badge: t("group.members", { n: entry.members.length }),
					caret: {
						expanded: open,
						label: open ? t("group.collapse", { name: entry.name }) : t("group.expand", { name: entry.name }),
						onToggle: () => toggleFamily(entry.name)
					},
					all: {
						label: t("group.all.label", { name: entry.name, n: entry.members.length }),
						pending: invoking === familyKey,
						disabled: invoking !== undefined && invoking !== familyKey,
						onClick: () => run(familyKey, [entry.skill.name, ...entry.members.map((member) => member.name)])
					}
				})
			);
			if (!open) continue;
			for (const member of entry.members) rows.push(h(SkillRow, { ...rowProps(member, member.name), nested: true }));
		}
		body = h(
			"ul",
			{ className: "dsl-skilllib-rows", "aria-label": t("list.label"), "aria-busy": state.status === "loading" ? "true" : void 0 },
			rows
		);
	}
	return h("div", { className: "dsl-skilllib-page" }, [
		h("div", { className: "dsl-skilllib-pageScroll", key: "scroll" }, [
			h("div", { className: "dsl-skilllib-pageContent", key: "content" }, [
				h("header", { className: "dsl-skilllib-head", key: "head" }, [
					h("div", { key: "titles" }, [
						h("h1", { className: "dsl-skilllib-title", key: "title" }, t("title")),
						h("p", { className: "dsl-skilllib-subtitle", key: "sub" }, sessionId === void 0 ? t("subtitle") : `${t("subtitle")} · ${t("subtitle.from", { title: sessionTitle })}`)
					]),
					h(
						"div",
						{ className: "dsl-skilllib-headActions", key: "actions" },
						h(
							primitives.Button,
							{
								variant: "outline",
								size: "sm",
								icon: h(primitives.IconRefreshOutlineRegular, { size: 13 }),
								"aria-label": t("refresh.label"),
								disabled: sessionId === void 0 || state.status === "loading",
								onClick: refresh
							},
							t("refresh")
						)
					)
				]),
				h(
					"div",
					{ className: "dsl-skilllib-search", key: "search" },
					h(primitives.IconSearchOutlineRegular, { size: 14, key: "icon" }),
					h("input", {
						key: "input",
						type: "search",
						value: query,
						placeholder: t("search.placeholder"),
						"aria-label": t("search.label"),
						onChange: (event) => {
							setQuery(event.target.value);
						}
					}),
					query === ""
						? null
						: h(
								"button",
								{
									key: "clear",
									type: "button",
									className: "dsl-skilllib-clear",
									"aria-label": t("search.clear"),
									onClick: () => {
										setQuery("");
									}
								},
								h(primitives.IconCloseFillRegular, { size: 12 })
							)
				),
				state.status === "ready" && state.rows.length > 0 ? h("p", { className: "dsl-skilllib-count", key: "count" }, t("count", { n: visibleCount })) : null,
				h("div", { className: "dsl-skilllib-body", key: "body" }, body),
				h("p", { className: "dsl-skilllib-hint", key: "hint" }, t("hint.invoke"))
			])
		])
	]);
}
